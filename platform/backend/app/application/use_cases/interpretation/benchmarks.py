"""Controlled validation of a ruleset version's engine behaviour.

This is deliberately modest, and the modesty is the point. A benchmark run here
compares *stored expected outputs* of controlled cases against *what the engine
returned* for the same inputs. That verifies determinism, contract shape and
rule-version attribution. It is not a clinical accuracy measurement, and the
platform refuses to present it as one:

* a case is ``SCIENTIFIC_ACCURACY`` only when its expected outputs come from a
  declared external reference corpus named on the case itself;
* a run is reported as an accuracy run only when every case it executed was such a
  case — otherwise it is reported as contract/determinism validation;
* no score, sensitivity, specificity or concordance percentage is invented, and no
  expected output is ever generated by the platform.

Comparison is equality of stored values. Nothing here computes a criterion or a
classification.
"""

