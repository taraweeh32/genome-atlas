@dataclass(frozen=True, slots=True)
class RegisterBenchmarkCaseCommand:
    actor: ActorContext
    request: RequestContext
    ruleset_id: str
    case_key: str
    validation_kind: BenchmarkValidationKind
    input_snapshot: dict[str, Any]
    expected_criteria: dict[str, Any] | None = None
    expected_classification: Classification | None = None
    description: str | None = None
    source_reference: str | None = None


@dataclass(frozen=True, slots=True)
class ObservedCaseOutcome:
    """What the engine returned for one case, as delivered by the caller.

    Supplied by whoever ran the cases through the scientific boundary — a harness
    or an operator — never produced here.
    """

    case_key: str
    observed_classification: str | None = None
    observed_criteria: dict[str, Any] | None = None
    not_evaluated: bool = False
    detail: str | None = None


@dataclass(frozen=True, slots=True)
class RecordBenchmarkRunCommand:
    actor: ActorContext
    request: RequestContext
    ruleset_id: str
    observations: tuple[ObservedCaseOutcome, ...]


class RegisterBenchmarkCase:
    """Register one controlled case against one ruleset version."""

    def __init__(self, services: InterpretationServices) -> None:
        self._services = services

    async def execute(
        self, command: RegisterBenchmarkCaseCommand
    ) -> BenchmarkCaseRecord:
        now = self._services.clock.now()
        if not command.input_snapshot:
            raise ValidationError(
                "a benchmark case requires an input fixture",
                details={"field": "input_snapshot"},
            )
        async with self._services.unit_of_work.begin() as repositories:
            recorder = ActivityRecorder(repositories, command.request)
            await require_platform_administration(
                self._services, command.actor, recorder=recorder, occurred_at=now
            )
            ruleset = await repositories.rulesets.get(command.ruleset_id)
            if ruleset is None:
                raise NotFoundError("interpretation_ruleset", command.ruleset_id)
            existing = await repositories.ruleset_benchmarks.get_case_by_key(
                ruleset_id=command.ruleset_id, case_key=command.case_key
            )
            if existing is not None:
                raise ConflictError(
                    "this benchmark case is already registered for this ruleset "
                    "version",
                    details={"case_key": command.case_key},
                )
            unknown = [
                key
                for key in (command.expected_criteria or {})
                if ruleset.criterion(key) is None
            ]
            if unknown:
                raise ValidationError(
                    "the case expects a criterion this ruleset version does not "
                    "declare",
                    details={"criterion_key": unknown[0]},
                )
            case = BenchmarkCaseRecord(
                id=new_id("bcs"),
                ruleset_id=command.ruleset_id,
                case_key=command.case_key,
                validation_kind=command.validation_kind,
                input_snapshot=dict(command.input_snapshot),
                expected_criteria=dict(command.expected_criteria or {}),
                expected_classification=command.expected_classification,
                description=command.description,
                source_reference=command.source_reference,
                created_by=command.actor.actor_id,
                created_at=now,
            )
            stored = await repositories.ruleset_benchmarks.add_case(case)
            await recorder.audit(
                action="ruleset_benchmark_case.registered",
                outcome=AuditOutcome.SUCCESS,
                occurred_at=now,
                actor_user_id=command.actor.actor_id,
                resource_type="ruleset_benchmark_case",
                resource_id=stored.id,
                detail={
                    "ruleset_id": stored.ruleset_id,
                    "case_key": stored.case_key,
                    "validation_kind": stored.validation_kind.value,
                    "source_reference": stored.source_reference,
                },
            )
            await recorder.event(
                event_type=EventType.RULESET_BENCHMARK_CASE_REGISTERED,
                aggregate_type="ruleset_benchmark_case",
                aggregate_id=stored.id,
                occurred_at=now,
                payload={
                    "ruleset_id": stored.ruleset_id,
                    "validation_kind": stored.validation_kind.value,
                },
            )
            return stored


def compare_case(
    case: BenchmarkCaseRecord, observation: ObservedCaseOutcome | None
) -> BenchmarkComparison:
    """Compare one case's stored expectation to one observed outcome."""
    expected_classification = (
        case.expected_classification.value if case.expected_classification else None
    )
    if observation is None or observation.not_evaluated:
        return BenchmarkComparison(
            case_id=case.id,
            case_key=case.case_key,
            outcome=BenchmarkCaseOutcome.NOT_EVALUATED,
            validation_kind=case.validation_kind,
            expected_classification=expected_classification,
            observed_classification=None,
            severity=ValidationSeverity.WARNING,
            detail=(observation.detail if observation else "no outcome was reported"),
        )
    differences: list[dict[str, Any]] = []
    for criterion_key, expected in case.expected_criteria.items():
        observed = (observation.observed_criteria or {}).get(criterion_key)
        if observed != expected:
            differences.append(
                {
                    "criterion_key": criterion_key,
                    "expected": expected,
                    "observed": observed,
                }
            )
    classification_matches = (
        expected_classification is None
        or expected_classification == observation.observed_classification
    )
    matched = classification_matches and not differences
    return BenchmarkComparison(
        case_id=case.id,
        case_key=case.case_key,
        outcome=BenchmarkCaseOutcome.MATCHED if matched else BenchmarkCaseOutcome.MISMATCHED,
        validation_kind=case.validation_kind,
        expected_classification=expected_classification,
        observed_classification=observation.observed_classification,
        criterion_differences=tuple(differences),
        severity=ValidationSeverity.INFO if matched else ValidationSeverity.ERROR,
        detail=observation.detail,
    )


class RecordBenchmarkRun:
    """Compare reported outcomes to the stored cases and record the run."""

    def __init__(self, services: InterpretationServices) -> None:
        self._services = services

    async def execute(self, command: RecordBenchmarkRunCommand) -> BenchmarkRunRecord:
        now = self._services.clock.now()
        async with self._services.unit_of_work.begin() as repositories:
            recorder = ActivityRecorder(repositories, command.request)
            await require_platform_administration(
                self._services, command.actor, recorder=recorder, occurred_at=now
            )
            ruleset = await repositories.rulesets.get(command.ruleset_id)
            if ruleset is None:
                raise NotFoundError("interpretation_ruleset", command.ruleset_id)
            cases = await repositories.ruleset_benchmarks.list_cases(
                ruleset_id=command.ruleset_id
            )
            if not cases:
                raise ValidationError(
                    "this ruleset version has no active benchmark cases",
                    details={"ruleset_id": command.ruleset_id},
                )
            observed = {item.case_key: item for item in command.observations}
            unknown = [key for key in observed if key not in {c.case_key for c in cases}]
            if unknown:
                raise ValidationError(
                    "an outcome was reported for a case this ruleset version does "
                    "not declare",
                    details={"case_key": unknown[0]},
                )
            comparisons = tuple(
                compare_case(case, observed.get(case.case_key)) for case in cases
            )
            matched = sum(
                1 for item in comparisons if item.outcome is BenchmarkCaseOutcome.MATCHED
            )
            mismatched = sum(
                1
                for item in comparisons
                if item.outcome is BenchmarkCaseOutcome.MISMATCHED
            )
            not_evaluated = sum(
                1
                for item in comparisons
                if item.outcome is BenchmarkCaseOutcome.NOT_EVALUATED
            )
            executed = tuple(
                item
                for item in comparisons
                if item.outcome is not BenchmarkCaseOutcome.NOT_EVALUATED
            )
            # An accuracy claim requires *every* executed case to be an accuracy
            # case with a declared reference corpus. Anything else is contract
            # validation and is labelled as such.
            is_accuracy_run = bool(executed) and all(
                item.validation_kind is BenchmarkValidationKind.SCIENTIFIC_ACCURACY
                for item in executed
            )
            run = BenchmarkRunRecord(
                id=new_id("brn"),
                ruleset_id=ruleset.id,
                ruleset_key=ruleset.ruleset_key,
                ruleset_version=ruleset.version,
                validation_kind=BenchmarkValidationKind.SCIENTIFIC_ACCURACY
                if is_accuracy_run
                else BenchmarkValidationKind.CONTRACT,
                case_count=len(cases),
                matched_count=matched,
                mismatched_count=mismatched,
                not_evaluated_count=not_evaluated,
                comparisons=comparisons,
                is_accuracy_run=is_accuracy_run,
                executed_by=command.actor.actor_id,
                executed_at=now,
                created_at=now,
            )
            stored = await repositories.ruleset_benchmarks.add_run(run)
            await recorder.audit(
                action="ruleset_benchmark.executed",
                outcome=AuditOutcome.SUCCESS
                if mismatched == 0
                else AuditOutcome.FAILURE,
                occurred_at=now,
                actor_user_id=command.actor.actor_id,
                resource_type="ruleset_benchmark_run",
                resource_id=stored.id,
                detail={
                    "ruleset_key": stored.ruleset_key,
                    "ruleset_version": stored.ruleset_version,
                    "validation_kind": stored.validation_kind.value,
                    "is_accuracy_run": stored.is_accuracy_run,
                    "matched": matched,
                    "mismatched": mismatched,
                    "not_evaluated": not_evaluated,
                },
            )
            await recorder.event(
                event_type=EventType.RULESET_BENCHMARK_EXECUTED,
                aggregate_type="ruleset_benchmark_run",
                aggregate_id=stored.id,
                occurred_at=now,
                payload={
                    "ruleset_id": stored.ruleset_id,
                    "validation_kind": stored.validation_kind.value,
                    "is_accuracy_run": stored.is_accuracy_run,
                },
            )
            return stored


@dataclass(frozen=True, slots=True)
class BenchmarkReader:
    """Governance-level reads of benchmark cases and runs."""

    services: InterpretationServices

    async def list_cases(
        self,
        actor: ActorContext,
        request: RequestContext,
        *,
        ruleset_id: str,
        validation_kind: BenchmarkValidationKind | None = None,
    ) -> tuple[BenchmarkCaseRecord, ...]:
        now = self.services.clock.now()
        async with self.services.unit_of_work.begin() as repositories:
            recorder = ActivityRecorder(repositories, request)
            await require_platform_read(
                self.services, actor, recorder=recorder, occurred_at=now
            )
            return await repositories.ruleset_benchmarks.list_cases(
                ruleset_id=ruleset_id, validation_kind=validation_kind
            )

    async def list_runs(
        self,
        actor: ActorContext,
        request: RequestContext,
        *,
        ruleset_id: str,
        page: Page,
    ) -> Paged[BenchmarkRunRecord]:
        now = self.services.clock.now()
        async with self.services.unit_of_work.begin() as repositories:
            recorder = ActivityRecorder(repositories, request)
            await require_platform_read(
                self.services, actor, recorder=recorder, occurred_at=now
            )
            return await repositories.ruleset_benchmarks.list_runs(
                ruleset_id=ruleset_id, page=page
            )


